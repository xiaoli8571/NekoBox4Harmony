// Static ABI/lifecycle guards; actual C++ compilation is also required by release validation.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const cpp=fs.readFileSync(path.join(root,'entry/src/main/cpp/napi_init.cpp'),'utf8');
const types=fs.readFileSync(path.join(root,'entry/src/main/cpp/types/libentry/index.d.ts'),'utf8');
const creates=[...cpp.matchAll(/napi_create_threadsafe_function\([\s\S]*?\);/g)];
assert.equal(creates.length,1,'all one-shot TSFNs must share the checked factory');
assert.match(creates[0][0],/resName, 0, 1,/,'single producer must have one releaseable reference');
assert.match(cpp,/if \(env == nullptr \|\| jsCb == nullptr\)/,'environment shutdown drains queued data without JS');
assert.ok(!cpp.includes('usleep('),'TSFN release must not rely on arbitrary sleeps');
console.log('PASS static TSFN reference balance and environment shutdown guards');
const start=cpp.slice(cpp.indexOf('static napi_value StartCoreNative'),cpp.indexOf('// testStartNative'));
assert.ok(start.includes('napi_threadsafe_function tsf = CreateResultTsf'));
assert.ok(!start.includes('napi_call_function'),'no reentrant JS under native state lock');
assert.match(start,/cancelled = generation <= g_cancelledGeneration;[\s\S]*?g_coreState.store\(message.empty\(\) && !cancelled/);
const stop=cpp.slice(cpp.indexOf('static napi_value StopCoreNative'),cpp.indexOf('static napi_value IsCoreRunning'));
assert.match(stop,/g_stopWaiters.push_back\(tsf\)/);
assert.match(stop,/state == CoreState::Starting[\s\S]*?g_cancelledGeneration = g_coreGeneration;[\s\S]*?return nullptr;/);
assert.match(stop,/CompleteWaiters\(message\)/);
assert.ok(!stop.includes('compare_exchange_strong'),'state decisions must share cancellation mutex');
console.log('PASS static startup cancellation and stop acknowledgement ordering');
assert.match(cpp,/std::isfinite\(v\)/);assert.match(cpp,/std::trunc\(v\)/);assert.match(cpp,/numeric_limits<int>::max/);
const names=[...cpp.matchAll(/\{"([^"]+)", nullptr, \w+, nullptr/g)].map(m=>m[1]);
for(const name of names)assert.match(types,new RegExp('export const '+name+'\\s*:'));
assert.match(types,/testStartNative: \(configPath: string, bindIfname: string,/);
assert.match(types,/timeoutMs: number, expectStatus: string,/);
console.log('PASS static NAPI numeric boundary guards and all '+names.length+' exported type contracts');
